def _get_mock_carbon_intensity(hour_of_day: int) -> float:
    """Mock function to get carbon intensity (kgCO2/kWh) based on hour."""
    # Simulate lower intensity during off-peak and higher during peak
    if 0 <= hour_of_day < 6: # Night
        return 0.15
    elif 6 <= hour_of_day < 10: # Morning peak
        return 0.35
    elif 10 <= hour_of_day < 17: # Day off-peak
        return 0.20
    elif 17 <= hour_of_day < 22: # Evening peak
        return 0.45
    else: # Late night
        return 0.25

def _get_mock_price_per_kwh(hour_of_day: int) -> float:
    """Mock function to get price per kWh (pence/kWh) based on hour."""
