@app.post("/optimize_appliance", summary="Find optimal time to run an appliance")
async def optimize_appliance(request: ApplianceOptimizationRequest):
    """
    Finds the optimal hour within a flexible window to run an appliance
    to minimize a weighted combination of energy cost and carbon footprint.
    """
    if request.flexible_start_hour > request.flexible_end_hour:
        raise HTTPException(status_code=400, detail="Flexible start hour cannot be after end hour.")

    best_hour = -1
    min_objective_value = float('inf')
    predictions_and_costs = []

    # Iterate through each hour in the flexible window
    for current_hour in range(request.flexible_start_hour, request.flexible_end_hour + 1):
        # 1. Prepare input for baseline energy prediction for this hour
        prediction_date = request.optimization_date
        day_of_week = prediction_date.weekday()
        month = prediction_date.month
        season = (month % 12 + 3) // 3
        day_of_year_sin = np.sin(2 * np.pi * prediction_date.timetuple().tm_yday/365)
        day_of_year_cos = np.cos(2 * np.pi * prediction_date.timetuple().tm_yday/365)

        # Derived features based on current hour's weather data
        temp_humidity = request.max_temp_c * request.humidity_percent
        temp_wind = request.max_temp_c * request.wind_speed_km_h
        weather_severity = (request.max_temp_c * 0.3 + request.rain_mm * 0.2 + request.wind_speed_km_h * 0.5)
        size_rating = request.total_floor_area * request.current_energy_rating
        # age_size is tricky without knowing the OneHotEncoder's mapping for CONSTR_AGE_BAND
        # For simplicity, using a fixed value for demo, assuming its impact is consistent
        # In a real system, you'd need the actual numeric code from the preprocessor for this categorical.
        age_size_val = 5000.0 # Placeholder, adjust if you have a mapping

        input_data_for_baseline = {
            "min_temp_c": request.min_temp_c,
            "max_temp_c": request.max_temp_c,
            "rain_mm": request.rain_mm,
            "humidity_%": request.humidity_percent,
            "cloud_cover_%": request.cloud_cover_percent,
            "wind_speed_km/h": request.wind_speed_km_h,
            "wind_direction_numerical": request.wind_direction_numerical,
            "TOTAL_FLOOR_AREA": request.total_floor_area,
            "CURRENT_ENERGY_RATING": request.current_energy_rating,
            "BUILT_FORM": request.built_form,
            "PROPERTY_TYPE": request.property_type,
            "CONSTRUCTION_AGE_BAND": request.construction_age_band,
            "day_of_week": day_of_week,
            "month": month,
            "season": season,
            "day_of_year_sin": float(day_of_year_sin),
            "day_of_year_cos": float(day_of_year_cos),
            "hour_of_day": current_hour, # This changes per iteration
            "temp_humidity": temp_humidity,
            "temp_wind": temp_wind,
            "weather_severity": weather_severity,
            "size_rating": size_rating,
            "age_size": age_size_val, # Using placeholder
            "lag_1": request.lag_1,
            "lag_2": request.lag_2,
            "lag_3": request.lag_3,
            "lag_7": request.lag_7,
            "rolling_7day_mean": request.rolling_7day_mean,
            "rolling_7day_std": request.rolling_7day_std
        }

        # Ensure all features in `features_list` are present in `input_data_for_baseline`
        # and are in the correct order. This is critical for `preprocessor.transform`.
        # Create a DataFrame ensuring column order.
        try:
            input_df = pd.DataFrame([input_data_for_baseline])[features_list]
        except KeyError as e:
            raise HTTPException(status_code=500, detail=f"Missing feature in input data for baseline prediction: {e}. "
                                                        "This is likely due to a mismatch between API request fields "
                                                        "and the model's expected features_list.")

        # Preprocess the input data
        processed_input = preprocessor.transform(input_df)

        # Get baseline energy prediction
        xgb_pred = best_xgb_regressor.predict(processed_input)
        lgbm_pred = best_lgbm_regressor.predict(processed_input)
        stacked_predictions = np.column_stack([xgb_pred, lgbm_pred])
        baseline_kwh = meta_model.predict(stacked_predictions)[0]

        # 2. Add appliance consumption to baseline
        total_kwh_with_appliance = baseline_kwh + request.appliance_kwh_per_cycle

        # 3. Get mock carbon intensity and price for this hour
        carbon_intensity = _get_mock_carbon_intensity(current_hour)
        price_per_kwh = _get_mock_price_per_kwh(current_hour)

        # 4. Calculate total cost and carbon for this hour
        total_cost = total_kwh_with_appliance * price_per_kwh / 100 # Convert pence to pounds
        total_carbon = total_kwh_with_appliance * carbon_intensity

        # 5. Calculate objective value (weighted sum of cost and carbon)
        # Normalize cost and carbon if their scales are vastly different
        # For this demo, assuming similar scale or that the weights handle it.
        # In a real scenario, you might want to normalize cost and carbon to a 0-1 scale
        # before applying weights, to ensure fair weighting.
        objective_value = (request.cost_weight * total_cost) + (request.carbon_weight * total_carbon)

        predictions_and_costs.append({
            "hour": current_hour,
            "baseline_kwh": float(baseline_kwh),
            "appliance_kwh": float(request.appliance_kwh_per_cycle),
            "total_kwh": float(total_kwh_with_appliance),
            "carbon_intensity_kgCO2_per_kWh": float(carbon_intensity),
            "price_pence_per_kWh": float(price_per_kwh),
            "total_cost_pounds": float(total_cost),
            "total_carbon_kgCO2": float(total_carbon),
            "objective_value": float(objective_value)
        })

        # 6. Check for optimal hour
        if objective_value < min_objective_value:
            min_objective_value = objective_value
            best_hour = current_hour

    # Find the details for the best hour
    best_hour_details = next((item for item in predictions_and_costs if item["hour"] == best_hour), None)

    return {
        "optimization_date": request.optimization_date.isoformat(),
        "appliance_name": request.appliance_name,
        "flexible_window": f"{request.flexible_start_hour}:00 - {request.flexible_end_hour}:00",
        "optimal_hour_to_run": best_hour,
        "optimal_hour_details": best_hour_details,
        "all_hours_details": predictions_and_costs,
        "message": f"To minimize cost and carbon for your {request.appliance_name}, the optimal time to run it is at {best_hour}:00 on {request.optimization_date.isoformat()}."
    }

