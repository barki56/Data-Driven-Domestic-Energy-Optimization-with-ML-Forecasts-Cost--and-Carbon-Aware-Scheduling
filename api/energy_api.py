@app.post("/predict", summary="Predict energy consumption (kWh)")
async def predict_energy_consumption(request: EnergyPredictRequest):
    """
    Predicts energy consumption (kWh) based on the provided input features.
    """
    try:
        input_data_dict = request.model_dump(by_alias=True)
        input_df = pd.DataFrame([input_data_dict])[features_list] # Ensure order matches training

        processed_input = preprocessor.transform(input_df)

        xgb_pred = best_xgb_regressor.predict(processed_input)
        lgbm_pred = best_lgbm_regressor.predict(processed_input)
        stacked_predictions = np.column_stack([xgb_pred, lgbm_pred])

        final_prediction = meta_model.predict(stacked_predictions)[0]

        return {"predicted_kwh": float(final_prediction)}

    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Prediction failed: {e}")


